/// Registers every metric so each appears in the first scrape, even at zero.
pub fn init() {
    BUILD_INFO.with_label_values(&[env!("CARGO_PKG_VERSION")]).set(1);
    LazyLock::force(&REQUESTS);
    LazyLock::force(&UPSTREAM_DURATION);
    LazyLock::force(&REQUEST_BYTES);
    LazyLock::force(&RESPONSE_BYTES);
    LazyLock::force(&ACTIVE_REQUESTS);
    LazyLock::force(&USAGE_PENDING);
    LazyLock::force(&USAGE_DROPPED);
    LazyLock::force(&USAGE_FLUSH_FAILURES);
    LazyLock::force(&ACCESS_LOG_DROPPED);
    LazyLock::force(&DURATION);
    LazyLock::force(&GATEWAY_ERRORS);
    LazyLock::force(&LIMITED);
    LazyLock::force(&PLUGIN_ERRORS);
    LazyLock::force(&TRANSFORM_SKIPPED);
    LazyLock::force(&CACHE_BYTES);
    for result in ["hit", "miss", "bypass"] {
        CACHE_REQUESTS.with_label_values(&[result]).inc_by(0);
    }
    LazyLock::force(&UPSTREAM_FAIL_OPEN);
    LazyLock::force(&UPSTREAM_RETRIES);
    LazyLock::force(&BACKEND_HEALTHY);
    LazyLock::force(&BACKEND_CIRCUIT_OPEN);
    LazyLock::force(&DNS_FAILURES);
    LazyLock::force(&ACME_ISSUANCES);
    LazyLock::force(&ACME_FAILURES);
    for within in ["7d", "14d", "30d"] {
        CERTS_EXPIRING.with_label_values(&[within]).set(0);
    }
    LazyLock::force(&CONFIG_CONVERGED);
    LazyLock::force(&CONFIG_APPLIED_SEQ);
    LazyLock::force(&CONFIG_SOURCE_AGE);
    LazyLock::force(&CONFIG_RESOURCES);
    LazyLock::force(&CONFIG_DANGLING);
    LazyLock::force(&CONFIG_RELOAD_FAILURES);
    LazyLock::force(&CHANGELOG_ERRORS);
    LazyLock::force(&SNAPSHOTS);
}

/// `2xx`, `3xx`, `4xx` or `5xx`.
pub fn status_class(status: u16) -> &'static str {
    match status {
        200..=299 => "2xx",
        300..=399 => "3xx",
        400..=499 => "4xx",
        _ => "5xx",
    }
}

/// The text exposition of every registered metric.
pub fn gather() -> String {
    let mut buf = Vec::new();
    let _ = TextEncoder::new().encode(&prometheus::gather(), &mut buf);
    String::from_utf8(buf).unwrap_or_default()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn exposition_names_the_documented_metrics() {
        init();
        GATEWAY_ERRORS.with_label_values(&["NO_ROUTE"]).inc();
        REQUESTS.with_label_values(&["orders", "orders-svc", "2xx"]).inc();
        let text = gather();
        for name in ["apg_requests_total", "apg_gateway_errors_total{code=\"NO_ROUTE\"}", "apg_config_converged", "apg_config_applied_seq", "apg_build_info"] {
            assert!(text.contains(name), "missing {name}");
        }
        assert_eq!(status_class(204), "2xx");
        assert_eq!(status_class(308), "3xx");
        assert_eq!(status_class(404), "4xx");
        assert_eq!(status_class(503), "5xx");
        assert_eq!(status_class(0), "5xx");
        assert!(text.contains("apg_requests_total{route=\"orders\",service=\"orders-svc\",status_class=\"2xx\"}"));
    }

    // spec OBS-1
    #[test]
    fn label_pairs_beyond_the_limit_collapse_into_other() {
        // Other tests in this process may have used pairs already; leave room for exactly two more.
        assert_eq!(series("cap-a", "s"), ("cap-a", "s"));
        set_max_series(SERIES.len() + 1);
        assert_eq!(series("cap-b", "s"), ("cap-b", "s"));
        assert_eq!(series("cap-c", "s"), ("_other", "_other"), "a new pair past the limit");
        assert_eq!(series("cap-a", "s"), ("cap-a", "s"), "a known pair keeps its labels");
        set_max_series(10_000);
    }
}
