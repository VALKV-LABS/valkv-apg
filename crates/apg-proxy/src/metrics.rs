static SERIES: LazyLock<dashmap::DashSet<u64>> = LazyLock::new(dashmap::DashSet::new);
static MAX_SERIES: std::sync::atomic::AtomicUsize = std::sync::atomic::AtomicUsize::new(10_000);

/// Sets how many (route, service) label pairs are kept (`APG_METRICS_MAX_SERIES`).
pub fn set_max_series(max: usize) {
    MAX_SERIES.store(max, std::sync::atomic::Ordering::Relaxed);
}

/// The labels to count a request under. Once the node holds the configured
/// number of pairs, new ones collapse into `_other`, so a tenant creating
/// routes cannot grow the node's metrics without bound (spec OBS-1).
pub fn series<'a>(route: &'a str, service: &'a str) -> (&'a str, &'a str) {
    let key = crate::upstream::hash_parts(&[route, service]);
    if SERIES.contains(&key) {
        return (route, service);
    }
    if SERIES.len() >= MAX_SERIES.load(std::sync::atomic::Ordering::Relaxed) {
        return ("_other", "_other");
    }
    SERIES.insert(key);
    (route, service)
}

