//! Prometheus metrics (spec Appendix C).
//!
//! Phase 2a exports the request and configuration metrics. Per-route labels,
//! usage and the remaining Appendix C metrics arrive with their features.

use std::sync::LazyLock;

use prometheus::{Encoder, HistogramVec, IntCounter, IntCounterVec, IntGauge, IntGaugeVec, TextEncoder, register_histogram_vec, register_int_counter, register_int_counter_vec, register_int_gauge, register_int_gauge_vec};

pub static REQUESTS: LazyLock<IntCounterVec> =
    LazyLock::new(|| register_int_counter_vec!("apg_requests_total", "Requests handled, by status class.", &["status_class"]).unwrap());

pub static DURATION: LazyLock<HistogramVec> = LazyLock::new(|| {
    register_histogram_vec!(
        "apg_request_duration_seconds",
        "Time from request received to response sent.",
        &["status_class"],
        vec![0.001, 0.0025, 0.005, 0.01, 0.025, 0.05, 0.1, 0.25, 0.5, 1.0, 2.5, 5.0, 10.0]
    )
    .unwrap()
});

pub static GATEWAY_ERRORS: LazyLock<IntCounterVec> =
    LazyLock::new(|| register_int_counter_vec!("apg_gateway_errors_total", "Responses generated by the gateway itself, by error code.", &["code"]).unwrap());

pub static LIMITED: LazyLock<IntCounterVec> =
    LazyLock::new(|| register_int_counter_vec!("apg_limited_total", "Requests refused by a limit plugin.", &["type"]).unwrap());

pub static UPSTREAM_FAIL_OPEN: LazyLock<IntCounter> = LazyLock::new(|| {
    register_int_counter!("apg_upstream_fail_open_total", "Requests sent to a backend although every backend's circuit was open.").unwrap()
});

pub static UPSTREAM_RETRIES: LazyLock<IntCounterVec> = LazyLock::new(|| {
    register_int_counter_vec!("apg_upstream_retries_total", "Attempts made after a failed first attempt.", &["workspace", "service"]).unwrap()
});

pub static BACKEND_HEALTHY: LazyLock<IntGaugeVec> = LazyLock::new(|| {
    register_int_gauge_vec!("apg_backend_healthy", "1 while a backend passes its active health check, 0 while it fails.", &["workspace", "service", "backend"]).unwrap()
});

pub static BACKEND_CIRCUIT_OPEN: LazyLock<IntGaugeVec> = LazyLock::new(|| {
    register_int_gauge_vec!("apg_backend_circuit_open", "1 while a backend's circuit is open.", &["workspace", "service", "backend"]).unwrap()
});

pub static DNS_FAILURES: LazyLock<IntCounter> =
    LazyLock::new(|| register_int_counter!("apg_dns_failures_total", "Backend host names that failed to resolve.").unwrap());

pub static CONFIG_CONVERGED: LazyLock<IntGauge> =
    LazyLock::new(|| register_int_gauge!("apg_config_converged", "1 once the node has applied a complete configuration.").unwrap());

pub static CONFIG_APPLIED_SEQ: LazyLock<IntGauge> =
    LazyLock::new(|| register_int_gauge!("apg_config_applied_seq", "Sequence number of the newest change applied.").unwrap());

pub static CONFIG_SOURCE_AGE: LazyLock<IntGauge> =
    LazyLock::new(|| register_int_gauge!("apg_config_source_age_seconds", "Seconds since the config source was last known to be alive.").unwrap());

pub static CONFIG_RESOURCES: LazyLock<IntGaugeVec> =
    LazyLock::new(|| register_int_gauge_vec!("apg_config_resources", "Resources held, by kind.", &["kind"]).unwrap());

pub static CONFIG_DANGLING: LazyLock<IntGauge> =
    LazyLock::new(|| register_int_gauge!("apg_config_dangling_refs", "Routes held back because a service they name is missing.").unwrap());

pub static CONFIG_RELOAD_FAILURES: LazyLock<IntCounter> =
    LazyLock::new(|| register_int_counter!("apg_config_reload_failures_total", "Configuration reloads rejected as invalid.").unwrap());

pub static CHANGELOG_ERRORS: LazyLock<IntCounterVec> =
    LazyLock::new(|| register_int_counter_vec!("apg_changelog_errors_total", "Change events skipped, by reason.", &["kind"]).unwrap());

pub static SNAPSHOTS: LazyLock<IntCounterVec> =
    LazyLock::new(|| register_int_counter_vec!("apg_snapshots_total", "Full resyncs from the config source, by reason.", &["reason"]).unwrap());

pub static BUILD_INFO: LazyLock<IntGaugeVec> = LazyLock::new(|| register_int_gauge_vec!("apg_build_info", "Always 1; the version is a label.", &["version"]).unwrap());

/// Registers every metric so each appears in the first scrape, even at zero.
pub fn init() {
    BUILD_INFO.with_label_values(&[env!("CARGO_PKG_VERSION")]).set(1);
    for class in ["2xx", "3xx", "4xx", "5xx"] {
        REQUESTS.with_label_values(&[class]).inc_by(0);
    }
    LazyLock::force(&DURATION);
    LazyLock::force(&GATEWAY_ERRORS);
    LazyLock::force(&LIMITED);
    LazyLock::force(&UPSTREAM_FAIL_OPEN);
    LazyLock::force(&UPSTREAM_RETRIES);
    LazyLock::force(&BACKEND_HEALTHY);
    LazyLock::force(&BACKEND_CIRCUIT_OPEN);
    LazyLock::force(&DNS_FAILURES);
    LazyLock::force(&CONFIG_CONVERGED);
    LazyLock::force(&CONFIG_APPLIED_SEQ);
    LazyLock::force(&CONFIG_SOURCE_AGE);
    LazyLock::force(&CONFIG_RESOURCES);
    LazyLock::force(&CONFIG_DANGLING);
    LazyLock::force(&CONFIG_RELOAD_FAILURES);
    LazyLock::force(&CHANGELOG_ERRORS);
    LazyLock::force(&SNAPSHOTS);
}

/// `2xx`, `3xx`, `4xx` or `5xx`.
pub fn status_class(status: u16) -> &'static str {
    match status {
        200..=299 => "2xx",
        300..=399 => "3xx",
        400..=499 => "4xx",
        _ => "5xx",
    }
}

/// The text exposition of every registered metric.
pub fn gather() -> String {
    let mut buf = Vec::new();
    let _ = TextEncoder::new().encode(&prometheus::gather(), &mut buf);
    String::from_utf8(buf).unwrap_or_default()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn exposition_names_the_documented_metrics() {
        init();
        GATEWAY_ERRORS.with_label_values(&["NO_ROUTE"]).inc();
        let text = gather();
        for name in ["apg_requests_total", "apg_gateway_errors_total{code=\"NO_ROUTE\"}", "apg_config_converged", "apg_config_applied_seq", "apg_build_info"] {
            assert!(text.contains(name), "missing {name}");
        }
        assert_eq!(status_class(204), "2xx");
        assert_eq!(status_class(308), "3xx");
        assert_eq!(status_class(404), "4xx");
        assert_eq!(status_class(503), "5xx");
        assert_eq!(status_class(0), "5xx");
    }
}
