#!/usr/bin/env node
// Generates the reference pages of the documentation from the things they
// describe, so they cannot drift (spec DOC-2):
//
//   docs/src/reference/plugins/<type>.md   schemas/plugins/<type>.json + docs/fragments/plugins/<type>.md
//   docs/src/reference/configuration-file.md   schemas/apg-config.json and the resource schemas
//   docs/src/reference/admin-api.md        admin/openapi.json
//   docs/src/reference/cli.md              the help text in cli/src/run.ts
//   docs/src/reference/environment.md      schemas/process-config.yaml, limited to what the code reads
//   docs/src/reference/metrics.md          the metric registry in the node and the admin
//   docs/src/reference/error-codes.md      the error codes in the node and the admin
//
//   node tools/gen-docs.mjs            write the pages
//   node tools/gen-docs.mjs --check    exit 1 if a committed page differs from what would be written
//
// Needs Node 20 or newer and nothing else.

import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const read = (p) => readFileSync(join(root, p), "utf8");
const json = (p) => JSON.parse(read(p));
const out = new Map();
const NOTE = "<!-- Generated by tools/gen-docs.mjs. Do not edit: change the source it names and run `make docs`. -->\n\n";

// ── Schemas ──────────────────────────────────────────────────────────────────

const BASE = "https://schemas.invalid/";
const cache = new Map();
const load = (file) => {
  if (!cache.has(file)) cache.set(file, json(`schemas/${file}`));
  return cache.get(file);
};
function resolve(schema, file) {
  let s = schema;
  let at = file;
  for (let i = 0; i < 8 && typeof s?.$ref === "string"; i++) {
    const url = new URL(s.$ref, BASE + at);
    at = url.href.slice(BASE.length).split("#")[0];
    let doc = load(at);
    for (const part of url.hash.replace(/^#\/?/, "").split("/").filter(Boolean)) doc = doc?.[part];
    const { $ref: _r, ...siblings } = s;
    s = { ...doc, ...siblings };
  }
  return { schema: s ?? {}, file: at };
}

/** Descriptions are written for people who have never seen the requirements document. */
const plain = (text) => String(text ?? "").replace(/\s*\((?:spec )?§[^)]*\)/g, "").replace(/\s*\(spec [^)]*\)/g, "").replace(/\s*\([A-Z]{2,4}-\d+[a-z]?(?:, [A-Z]{2,4}-\d+[a-z]?)*\)/g, "").trim();
const cell = (text) => plain(text).replace(/\|/g, "\\|").replace(/\n/g, " ");
const code = (v) => `\`${typeof v === "string" ? v : JSON.stringify(v)}\``;

function typeOf(s) {
  if (s.const !== undefined) return code(s.const);
  if (s.enum) return s.enum.map(code).join(", ");
  if (s.oneOf || s.anyOf) {
    const kinds = [...new Set((s.oneOf ?? s.anyOf).map((b) => (b.type === "object" && b.required?.[0]?.startsWith("$") ? "secret" : b.type ?? "object")))];
    return kinds.join(" or ");
  }
  if (s.type === "array") return `list of ${s.items ? typeOf(s.items.$ref ? { type: "object" } : s.items).replace(/^list of /, "lists of ") : "values"}`;
  if (Array.isArray(s.type)) return s.type.join(" or ");
  const range = [s.minimum !== undefined ? `≥ ${s.minimum}` : "", s.maximum !== undefined ? `≤ ${s.maximum}` : ""].filter(Boolean).join(", ");
  return `${s.type ?? "object"}${range ? ` (${range})` : ""}`;
}

/** Rows of a field table: every settable key, nested keys dotted. */
function fields(schema, file, prefix = "", required = [], depth = 0) {
  const rows = [];
  const { schema: s, file: at } = resolve(schema, file);
  const props = { ...(s.properties ?? {}) };
  const need = new Set([...(s.required ?? []), ...required]);
  for (const branch of [...(s.oneOf ?? []), ...(s.anyOf ?? [])]) {
    const b = resolve(branch, at).schema;
    for (const [k, v] of Object.entries(b.properties ?? {})) if (!(k in props)) props[k] = v;
  }
  for (const [name, raw] of Object.entries(props)) {
    const p = resolve(raw, at);
    if (p.schema.readOnly === true) continue;
    const path = prefix ? `${prefix}.${name}` : name;
    const item = p.schema.type === "array" && p.schema.items ? resolve(p.schema.items, p.file) : null;
    const child = p.schema.properties && p.schema.type !== "array" ? p : item?.schema.properties ? item : null;
    rows.push({ path: item?.schema.properties ? `${path}[]` : path, type: child ? (item ? "list of objects" : "object") : typeOf(p.schema), required: need.has(name), default: p.schema.default, description: p.schema.description ?? "" });
    if (child && depth < 3) rows.push(...fields(child.schema, child.file, item ? `${path}[]` : path, [], depth + 1));
  }
  return rows;
}

function fieldTable(rows, skip = new Set()) {
  const lines = ["| Key | Type | Default | Description |", "|---|---|---|---|"];
  for (const r of rows.filter((x) => !skip.has(x.path))) {
    lines.push(`| \`${r.path}\`${r.required ? " (required)" : ""} | ${r.type} | ${r.default === undefined ? "" : code(r.default)} | ${cell(r.description)} |`);
  }
  return lines.join("\n");
}

// schemas/unbuilt.yaml without a YAML library.
const unbuilt = new Map();
{
  let section = "";
  let plugin = "";
  for (const line of read("schemas/unbuilt.yaml").split("\n")) {
    const top = /^([a-z_]+):/.exec(line);
    const sub = /^  ([a-z_]+):/.exec(line);
    const entry = /^\s+-\s*\{\s*path:\s*([A-Za-z0-9_.]+)/.exec(line);
    if (top) { section = top[1]; plugin = ""; }
    else if (sub && section === "plugins") plugin = sub[1];
    else if (entry) {
      const owner = section === "plugins" ? plugin : section;
      unbuilt.set(owner, [...(unbuilt.get(owner) ?? []), entry[1]]);
    }
  }
}
const notBuilt = (owner) => {
  const keys = unbuilt.get(owner) ?? [];
  return keys.length === 0 ? "" : `\n\n**Not available yet:** ${keys.map((k) => `\`${k}\``).join(", ")}. Setting ${keys.length === 1 ? "it" : "one of them"} to anything but the default is refused, in a file and through the Admin API alike, so nothing is accepted and then ignored.`;
};

// ── Plugins ──────────────────────────────────────────────────────────────────

const pluginTypes = [...read("admin/src/plugin-types.ts").matchAll(/\{ name: "([a-z_]+)", default_priority: (\d+), phases: \[([^\]]*)\] \}/g)]
  .map((m) => ({ name: m[1], priority: Number(m[2]), phases: m[3].replace(/"/g, "").split(",").map((s) => s.trim()) }));
const PHASE = {
  request: "before the request is forwarded", upstream_request: "as the request is sent upstream",
  response_headers: "when the response headers arrive", response_body: "as the response body passes", log: "after the response is sent",
};
const built = pluginTypes.filter((t) => existsSync(join(root, `schemas/plugins/${t.name}.json`)));

for (const t of built) {
  const schema = load(`plugins/${t.name}.json`);
  const fragment = `docs/fragments/plugins/${t.name}.md`;
  const off = new Set(unbuilt.get(t.name) ?? []);
  // A setting that only matters with a store that is not built is left out with it.
  const rows = fields(schema, `plugins/${t.name}.json`).filter((r) => !off.has(r.path) && !(off.has("store") && r.path === "fail_open"));
  out.set(`docs/src/reference/plugins/${t.name}.md`, [
    NOTE.trimEnd(), "",
    `# ${t.name}`, "",
    plain(schema.description), "",
    "| | |", "|---|---|",
    `| Runs | ${t.phases.map((p) => PHASE[p] ?? p).join("; ")} |`,
    `| Default priority | ${t.priority} (higher runs earlier) |`,
    `| Attach to | a route, a service, a workspace, or every request (\`global\`, system workspace only) |`,
    `| Switch off everywhere | flag \`plugin_${t.name}\` set to \`false\` |`, "",
    "## Configuration", "",
    rows.length === 0 ? "This plugin has no settings." : fieldTable(rows),
    notBuilt(t.name), "",
    existsSync(join(root, fragment)) ? read(fragment).trim() : "",
    "",
  ].join("\n"));
}

out.set("docs/src/reference/plugins/index.md", [
  NOTE.trimEnd(), "", "# Plugins", "",
  "A plugin is something the gateway does to a request or a response. Each instance is attached to a route, a service, a workspace or every request; when several of one type could apply, the most specific wins. See [plugin scopes and order](../../concepts/plugins.md).", "",
  "In the order they run by default:", "",
  "| Plugin | What it does | Priority |", "|---|---|---|",
  ...built.map((t) => `| [${t.name}](${t.name}.md) | ${cell(load(`plugins/${t.name}.json`).description)} | ${t.priority} |`),
  "",
  pluginTypes.length > built.length ? `Not available yet: ${pluginTypes.filter((t) => !built.includes(t)).map((t) => `\`${t.name}\``).join(", ")}.\n` : "",
].join("\n"));

// ── apg.yaml ─────────────────────────────────────────────────────────────────

